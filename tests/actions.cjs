const assert=require('node:assert/strict');
const {readImage}=require('./local-learning.cjs');
const {parse,notation}=require('../dist/engine');
require('../dist/board-templates');
require('../dist/action-buttons');
const vision=require('../dist/board-vision'),actions=require('../dist/actions');
const dir=process.argv[2]??'.vision-research';
const inspect=(name,mode)=>vision.inspect(readImage(dir,name),undefined,mode);
const chi=inspect('sample-chi2-6');
assert.equal(chi.phase,'response');
assert.deepEqual(chi.buttons,['chi','skip']);
assert.equal(chi.target.code,'7m');
assert.equal(chi.target.seat,0);
assert.equal(actions.compare(chi)[0].kind,'skip');
assert(chi.marks.some(m=>m.uncertain));
const after=inspect('sample-chi2-7');
assert(after.ok&&after.afterCall&&after.phase==='discard');
const pon=inspect('sample-pon-3','response');
assert(pon.three);
const choices=actions.compare({...pon,target:{seat:2,index:pon.rivers[2].length-1},offered:['pon']});
assert.deepEqual(choices.map(c=>c.kind),['pon','skip']);
assert(choices[0].yaku.includes('役牌白'));
assert.deepEqual(choices[0].forbidden,[31]);
assert.equal(inspect('sample-pon-4').phase,'discard');
assert(!inspect('sample-pon-7').ok);
const ankan=inspect('sample-kan-5');
assert(ankan.buttons.includes('kan'));
assert(actions.compare({...ankan,offered:['kan'],remaining:54}).some(c=>c.kind==='ankan'));
assert(!actions.compare({...ankan,offered:['kan'],remaining:0}).some(c=>c.kind==='ankan'));
const kakan=inspect('sample-kakan-2');
assert(actions.compare({...kakan,offered:['kan']}).some(c=>c.kind==='kakan'));
const open=inspect('sample-openkan-5','response');
// The target was omitted from the partial top river. Supply the visually
// labeled red 5s for the branch test, independent of the screenshot gate.
const daiminkan=actions.compare({...open,rivers:[parse('0s'),[],[],[]],target:{seat:0,index:0},offered:['kan'],remaining:42});
assert(daiminkan.some(c=>c.kind==='daiminkan'&&c.group.some(t=>t.red)));
const response={phase:'response',hand:parse('3456p123456s117z'),indicators:parse('8p'),
  rivers:[parse('4p'),[],[],[]],melds:[],ready:[false,false,false,false],offered:['chi'],target:{seat:0,index:0},remaining:40};
const variants=actions.compare(response).filter(c=>c.kind==='chi');
assert.equal(variants.length,2);
assert.deepEqual(variants.map(c=>c.group.map(t=>notation(t.id)).join('')).sort(),['3p4p5p','4p5p6p']);
assert(variants.every(c=>!c.forbidden.includes(c.cut.tile.id)));
assert(variants.some(c=>c.forbidden.includes(15)));
assert.throws(()=>actions.compare({...response,three:true}),/不一致/);
assert.throws(()=>actions.compare({...response,offered:['chi','ron']}),/荣和/);
assert.throws(()=>actions.compare({...response,remaining:0}),/不一致/);
const locked=parse('111m123p123s789s5z1m');
assert(actions.riichiKan(locked,[0,1,2,13],[],false));
assert(!actions.riichiKan(parse('1111m123p123s789s5z'),[0,1,2,3],[],false));
console.log('Live-button template, real screenshot branches, multi-chi, kuikae and riichi-kan regression passed.');
